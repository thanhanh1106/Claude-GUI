// Bỏ tiền tố "Error invoking remote method '...': Error: " để thông báo lỗi gọn gàng.
const inv = (ch) => (...a) => ipcRenderer.invoke(ch, ...a).catch((e) => {
  throw new Error(String((e && e.message) || e).replace(/^Error invoking remote method '[^']+': (?:\w*Error: )?/, ''));
});
const on = (channel) => (cb) => {
  const h = (_e, ...args) => cb(...args);
  ipcRenderer.on(channel, h);
  return () => ipcRenderer.removeListener(channel, h);
};

